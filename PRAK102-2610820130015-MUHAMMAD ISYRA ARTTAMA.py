# Definisi variabel
a = 4
b = 8
c = 3

# Menghitung kombinasi perkalian dan pembagian
hasil = (a * b) / c

# Menampilkan output
print(f"Variabel a bernilai {a}")
print(f"Variabel b bernilai {b}")
print(f"Variabel c bernilai {c}")
print(f"Hasil dari a dikali b dibagi c adalah {hasil:.6f}")